CAT_ORDER = ["金融","医疗健康","消费","汽车","TMT","传媒互联网",
             "新能源","高端制造","化工石化","金属矿产","建筑建材",
             "农林牧渔","交通物流","公用环保","综合概念"]

EXCLUDE_NAMES = {"综合行业","综合概念","综合指数"}

def _match_kw(name):
    for kws, cat in KW:
        for kw in kws:
            if kw in name:
                return cat
    return None

def main():
    # 加载 SW 映射
    with open(os.path.join(_BASE,"data","qmt_sector_mapping.json")) as f:
        qm = json.load(f)
    bk_qmt = {}
    for name, info in qm.get("mapping",{}).items():
        code = info.get("code","")
        if code: bk_qmt[code] = info.get("qmt","")

    # 加载现有分类
    with open(os.path.join(_BASE,"static","board_classification.json")) as f:
        old = json.load(f)
    cats = old.get("categories",[]) if isinstance(old,dict) else old

    all_boards = []
    seen = set()
    for cat in cats:
        for b in cat.get("boards",[]):
            c = b["code"]
            if c not in seen:
                seen.add(c)
                all_boards.append(b)

    sw, kw, unmatched = 0, 0, 0
    result = {}

    for b in all_boards:
        code = b["code"]
        name = b["name"]
        if name in EXCLUDE_NAMES:
            continue
        qmt = bk_qmt.get(code,"")
        assigned = SW_TO_CAT.get(qmt)
        if assigned:
            sw += 1
        else:
            assigned = _match_kw(name)
            if assigned:
                kw += 1
            else:
                assigned = "综合概念"
                unmatched += 1
        result.setdefault(assigned,[]).append(dict(b))

    output = []
    for cn in CAT_ORDER:
        boards = result.get(cn,[])
        if not boards: continue
        boards.sort(key=lambda x: x["name"])
        ind = [b for b in boards if b.get("type")=="industry"]
        con = [b for b in boards if b.get("type")!="industry"]
        output.append({"name":cn,"boards":ind+con})

    out_path = os.path.join(_BASE,"static","board_classification.json")
    with open(out_path,"w",encoding="utf-8") as f:
        json.dump({"categories":output},f,ensure_ascii=False,indent=2)

    total = sum(len(c["boards"]) for c in output)
    print(f"Total: {total} boards in {len(output)} categories")
    print(f"SW: {sw}  KW: {kw}  Unmatched: {unmatched}")
    for c in output:
        b = c["boards"]
        ni = sum(1 for x in b if x.get("type")=="industry")
        print(f"  {c['name']:10s} {len(b):4d}  (I:{ni} C:{len(b)-ni})")
    print(f"\n-> {out_path}")

if __name__=="__main__":
    main()
